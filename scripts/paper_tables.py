#!/usr/bin/env python3
"""Turn the bytes-per-arc table of an analyze.py summary.md into a LaTeX table for the paper.

usage: paper_tables.py results/summary.md > bpa.tex
Only a representative subset of methods is kept (one column per method group).
"""
import re, sys

COLS = [  # (summary column, LaTeX header)
    ("classic:dijkstra", "Dijkstra"),
    ("classic:lemon-preflow", "Preflow"),
    ("classic:lemon-ns", "LEMON NS"),
    ("classic:gk:0.1", "GK $\\varepsilon{=}0.1$"),
    ("highs-dual", "HiGHS dual"),
    ("clp-primal", "Clp primal"),
    ("ortools-glop-primal", "GLOP primal"),
    ("highs-ipx-cross", "HiGHS IPX"),
    ("clp-barrier", "Clp barrier"),
    ("highs-pdlp", "HiGHS PDLP"),
    ("ortools-pdlp", "OR-Tools PDLP"),
    ("own-pdhg", "own PDHG"),
    ("own-prow", "prox.\\ Hildreth"),
]

lines = open(sys.argv[1]).read().splitlines()
i = next(k for k, l in enumerate(lines) if l.startswith("## Net memory per input arc"))
rows = [l for l in lines[i + 1:] if l.startswith("|")]
hdr = [c.strip() for c in rows[0].strip("|").split("|")]
idx = {name: hdr.index(name) for name, _ in COLS if name in hdr}
cols = [(n, h) for n, h in COLS if n in idx]


def cell(s):
    m = re.match(r"(\d+) \(m=(\d+)k\)", s.strip())
    return f"{int(m.group(1)):,}".replace(",", "\\,") if m else "--"


print("% generated by scripts/paper_tables.py from " + sys.argv[1].split("/")[-1] + "; do not edit")
print("\\begin{tabular}{l" + "r" * len(cols) + "}")
print("\\toprule")
print("family & " + " & ".join("\\rotatebox{75}{" + h + "}" for _, h in cols) + " \\\\")
print("\\midrule")
for r in rows[2:]:
    c = [x.strip() for x in r.strip("|").split("|")]
    print(c[0] + " & " + " & ".join(cell(c[idx[n]]) for n, _ in cols) + " \\\\")
print("\\bottomrule")
print("\\end{tabular}")
